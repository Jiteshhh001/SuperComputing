"""
AI Chat Page — Conversational interface with the LearnFlow AI agent.
Answers are grounded in the student's model outputs (DKT mastery, XGBoost gaps,
recommendations, study plan, progress) and generated by an OpenRouter LLM when
configured, with a data-driven offline fallback.
"""
import streamlit as st
from pathlib import Path
from datetime import datetime
import sys

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

QUICK_ACTIONS = [
    ("📊 Mastery", "What's my current mastery level across my concepts?"),
    ("🎯 Weak Topics", "Which topics am I most at risk in right now?"),
    ("📚 Recommend", "Recommend the best study resources for my weak areas"),
    ("📅 Study Plan", "Create a personalized 7-day study plan for me"),
    ("📈 Progress", "How am I doing? Show my progress report"),
]


def _history(student_id: int) -> list:
    histories = st.session_state.setdefault("chat_histories", {})
    return histories.setdefault(student_id, [])


def render():
    st.markdown('<div class="section-header">💬 AI Chat</div>', unsafe_allow_html=True)
    st.markdown(
        '<p style="color: #94A3B8;">Ask about your mastery, weak topics, resources, study plan '
        'or any study question. Answers use your model results and conversation memory.</p>',
        unsafe_allow_html=True,
    )

    student_id = st.session_state.get("selected_student")
    agent = st.session_state.get("agent")
    if not agent or student_id is None:
        st.warning("Agent not initialized. Select a student in the sidebar.")
        return

    # ── Header: status + clear ──────────────────────────────────────────
    llm_on = agent.llm.available
    col1, col2 = st.columns([4, 1])
    with col1:
        status = ("🟢 AI model connected" + (f" · `{agent.llm.last_model}`" if agent.llm.last_model else "")
                  if llm_on else "🟡 Offline mode — data-driven answers (add an OpenRouter key in Settings for full AI chat)")
        st.markdown(f"**Student #{student_id}** · 🧠 4-layer memory · {status}")
    with col2:
        if st.button("🗑️ Clear chat", key="clear_chat", use_container_width=True):
            _history(student_id).clear()
            agent.memory.conversation.clear(student_id)
            st.rerun()

    history = _history(student_id)

    # ── Messages ────────────────────────────────────────────────────────
    with st.chat_message("assistant", avatar="🤖"):
        st.markdown(
            f"👋 Hi! I'm **LearnFlow AI**, the learning assistant for **Student #{student_id}**. "
            "I can explain your mastery scores, show at-risk topics, recommend resources, build a "
            "7-day plan, report progress — or help with any study question."
        )
    for msg in history:
        with st.chat_message(msg["role"], avatar="🧑‍🎓" if msg["role"] == "user" else "🤖"):
            st.markdown(msg["content"])
            if msg.get("meta"):
                st.caption(msg["meta"])

    # ── Quick actions ───────────────────────────────────────────────────
    cols = st.columns(len(QUICK_ACTIONS))
    clicked = None
    for col, (label, prompt) in zip(cols, QUICK_ACTIONS):
        if col.button(label, key=f"quick_{label}", use_container_width=True):
            clicked = prompt

    user_input = st.chat_input("Ask LearnFlow AI anything about your learning...", key="chat_input")
    message = user_input or clicked
    if message:
        _send_message(agent, student_id, message)
        st.rerun()

    # ── Memory inspector ────────────────────────────────────────────────
    with st.expander("🧠 Agent Memory Inspector", expanded=False):
        tab_conv, tab_profile, tab_recs, tab_history = st.tabs(
            ["💬 Conversation", "👤 Profile", "📚 Recommendations", "📜 History"])
        with tab_conv:
            conv = agent.memory.conversation.get_history(student_id, last_n=10)
            if conv:
                for m in conv:
                    icon = "🧑‍🎓" if m["role"] == "user" else "🤖"
                    text = m["content"].replace("\n", " ")
                    st.markdown(f"{icon} `{m.get('timestamp', '')[11:16]}` {text[:160]}{'…' if len(text) > 160 else ''}")
            else:
                st.info("No conversation memory yet.")
        with tab_profile:
            st.text(agent.memory.profiles.get_summary(student_id))
        with tab_recs:
            st.text(agent.memory.recommendations.get_summary(student_id))
        with tab_history:
            st.text(agent.memory.history.get_weekly_summary(student_id))
            events = agent.memory.history.get_events(student_id, last_n=10)
            for e in reversed(events):
                st.markdown(f"- `{e.get('timestamp', '')[:16].replace('T', ' ')}` "
                            f"{e.get('event_type', '').replace('_', ' ').title()}")


def _send_message(agent, student_id: int, message: str):
    """Send a message to the agent and store both sides with metadata."""
    history = _history(student_id)
    history.append({"role": "user", "content": message, "timestamp": datetime.now().isoformat()})
    with st.spinner("LearnFlow AI is thinking…"):
        try:
            response = agent.chat(student_id, message)
            meta = agent.last_meta
            if meta.get("mode") == "llm":
                caption = f"🤖 {meta.get('model')} · tools: {', '.join(meta.get('tools', [])) or '—'}"
            else:
                reason = meta.get("llm_error") or "no API key"
                caption = f"📊 data-driven answer (AI model unavailable: {reason})"
        except Exception as e:
            response, caption = f"Sorry, something went wrong while answering: {e}", ""
    history.append({"role": "assistant", "content": response, "meta": caption,
                    "timestamp": datetime.now().isoformat()})
